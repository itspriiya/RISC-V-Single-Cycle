// ============================================================
// RISC-V SINGLE-CYCLE PROCESSOR TESTBENCH
// ============================================================

module tb_top;

reg clk;
reg reset;


// ============================================================
// PROCESSOR INSTANTIATION
// ============================================================

Top_Level uut(
    .clk(clk),
    .reset(reset)
);


// ============================================================
// CLOCK GENERATION
// ============================================================

always begin
    #5 clk = ~clk;
end


// ============================================================
// TEST PROGRAM
// ============================================================

initial begin

    clk = 1'b0;
    reset = 1'b1;

    // Hold reset
    #10;

    reset = 1'b0;


    // ========================================================
    // INSTRUCTION MEMORY INITIALIZATION
    // ========================================================


    // --------------------------------------------------------
    // I-TYPE INSTRUCTIONS
    // --------------------------------------------------------

    // addi x1, x0, 10
    // x1 = 10

    uut.Inst_Memory.I_Mem[0] =
        32'b00000000101000000000000010010011;


    // addi x2, x0, 20
    // x2 = 20

    uut.Inst_Memory.I_Mem[1] =
        32'b00000001010000000000000100010011;


    // --------------------------------------------------------
    // R-TYPE INSTRUCTIONS
    // --------------------------------------------------------

    // add x3, x1, x2
    // R-type
    // x3 = x1 + x2 = 30

    uut.Inst_Memory.I_Mem[2] =
        32'b00000000001000001000000110110011;


    // sub x4, x3, x1
    // R-type
    // x4 = x3 - x1 = 20

    uut.Inst_Memory.I_Mem[3] =
        32'b01000000000100011000001000110011;


    // and x5, x3, x2
    // R-type
    // x5 = x3 & x2 = 20

    uut.Inst_Memory.I_Mem[4] =
        32'b00000000001000011111001010110011;


    // or x6, x3, x2
    // R-type
    // x6 = x3 | x2 = 30

    uut.Inst_Memory.I_Mem[5] =
        32'b00000000001000011110001100110011;


    // ========================================================
    // REGISTER FILE INITIALIZATION
    // ========================================================

    // x0 is always zero
    uut.Reg_File.Registers[0] = 32'd0;


    // ========================================================
    // RUN SIMULATION
    // ========================================================

    #100;

    $finish;

end


// ============================================================
// WAVEFORM GENERATION
// ============================================================

initial begin

    $dumpfile("riscv.vcd");

    $dumpvars(0, tb_top);

end

endmodule